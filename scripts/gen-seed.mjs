// Generates supabase/seed.sql from the bundled demo catalog (src/data/catalog.ts).
// Keeps the SQL seed locked in sync with the storefront seed, skipping regulated
// products that are not compliance-approved. Run when the seed changes:
//   node scripts/gen-seed.mjs
import { readFileSync, writeFileSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { createHash } from 'node:crypto'

const require = createRequire(import.meta.url)
const ts = require('typescript')

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const src = readFileSync(join(root, 'src', 'data', 'catalog.ts'), 'utf8')
  .replace(/^import[^\n]*$/gm, '')

const js = ts.transpileModule(src, {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, isolatedModules: true },
}).outputText

const mod = { exports: {} }
new Function('module', 'exports', '"use strict";' + js)(mod, mod.exports)

const { CATEGORIES, PRODUCTS, PROMOS, DEFAULT_SETTINGS } = mod.exports

const sqlStr = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "''")}'`
/** SQL literal: strings inline, objects/arrays as compact JSON. */
const lit = (v) => (typeof v === 'string' ? sqlStr(v) : sqlStr(JSON.stringify(v)))
/** SQL literal for a Postgres text[] column (not JSON: '["a"]' is invalid array syntax). */
const sqlArray = (v) => `array[${(Array.isArray(v) ? v : []).map(sqlStr).join(',')}]::text[]`
/** Deterministic, valid UUID per stable key (md5-like but real uuid format). */
const uuidOf = (key) => {
  const hex = createHash('sha256').update('hh-seed:' + key).digest('hex').slice(0, 32).replace(/^(.{12})/, '9$1')
  return sqlStr(`${hex.slice(0, 8)}-${hex.slice(8, 12)}-4${hex.slice(13, 16)}-8${hex.slice(17, 20)}-${hex.slice(20, 32)}`)
}

const unapproved = PRODUCTS.filter((p) => p.regulated && p.regStatus !== 'approved')
const keep = PRODUCTS.filter((p) => !(p.regulated && p.regStatus !== 'approved'))

const L = []
L.push('-- ═══════════════════════════════════════════════════════════════')
L.push('-- Health Harmony — demo seed (generated by scripts/gen-seed.mjs)')
L.push('-- Run ONCE in the Supabase SQL editor, AFTER 0001 and 0002.')
L.push('-- Idempotent: FOUC/ON CONFLICT DO UPDATE — safe to re-run.')
L.push(`-- Skips ${unapproved.length} regulated product(s) awaiting compliance approval.`)
L.push('-- ═══════════════════════════════════════════════════════════════')
L.push('')
L.push('-- ── categories ─────────────────────────────────────────────────')
for (const c of CATEGORIES) {
  L.push(`insert into public.categories (id, slug, experience, label, "desc", sort, active)`)
  L.push(`values (${uuidOf('cat:' + c.slug)}, ${lit(c.slug)}, ${lit(c.experience)}, ${lit(c.label)}, ${lit(c.desc)}, ${c.sort}, ${c.active})`)
  L.push(`on conflict (slug) do update set label = excluded.label, "desc" = excluded."desc", sort = excluded.sort, active = excluded.active;`)
}
L.push('')
L.push('-- ── products ───────────────────────────────────────────────────')
const cols = 'slug, sku, category_slug, label, description, overview, ingredients, usage, brand, manufacturer, origin, price, compare_price, stock, images, badges, regulated, reg_status, age_18, active'
for (const p of keep) {
  const row = [
    lit(p.slug), lit(p.sku), lit(p.categorySlug), lit(p.label), lit(p.description),
    p.overview ? lit(p.overview) : 'null', p.ingredients ? lit(p.ingredients) : 'null', p.usage ? lit(p.usage) : 'null',
    lit(p.brand), p.manufacturer ? lit(p.manufacturer) : 'null', p.origin ? lit(p.origin) : 'null',
    Number(p.price).toFixed(2), p.comparePrice ? Number(p.comparePrice).toFixed(2) : 'null',
    String(Math.max(0, p.stock)), sqlArray(p.images), sqlArray(p.badges),
    String(!!p.regulated), lit(p.regStatus ?? 'off'), String(!!p.age18), 'true',
  ].join(', ')
  L.push(`insert into public.products (${cols})`)
  L.push(`values (${row})`)
  L.push(`on conflict (slug) do update set`)
  L.push(`  sku = excluded.sku, label = excluded.label, description = excluded.description,`)
  L.push(`  overview = excluded.overview, ingredients = excluded.ingredients, usage = excluded.usage,`)
  L.push(`  brand = excluded.brand, manufacturer = excluded.manufacturer, origin = excluded.origin,`)
  L.push(`  price = excluded.price, compare_price = excluded.compare_price, images = excluded.images,`)
  L.push(`  badges = excluded.badges, regulated = excluded.regulated, reg_status = excluded.reg_status, age_18 = excluded.age_18;`)
}
L.push('')
L.push('-- ── promos (storefront coupons) ────────────────────────────────')
for (const pr of PROMOS) {
  L.push(`insert into public.promos (code, kind, value, active)`)
  L.push(`values (${lit(pr.code)}, ${lit(pr.kind)}, ${Number(pr.value).toFixed(2)}, ${pr.active})`)
  L.push(`on conflict (code) do update set kind = excluded.kind, value = excluded.value, active = excluded.active;`)
}
L.push('')
L.push('-- ── storefront settings (shipping, payments, VAT, banners) ─────')
const settings = { ...DEFAULT_SETTINGS }
// banner links point at real routes; the editor below lets the admin re-point them
settings.banners = (settings.banners ?? []).map((b) => ({ ...b, ctaLink: '/shop' }))
L.push(`insert into public.site_settings (key, value)`)
L.push(`values ('storefront', ${lit(settings)})`)
L.push(`on conflict (key) do update set value = excluded.value, updated_at = now();`)
L.push('')
L.push('-- NOTE: the seeded bank name/IBAN are placeholders (مثال/example):')
L.push('-- the storefront hides bank transfer until the admin sets real details.')
L.push('')
L.push('-- ═══════════════════════════════════════════════════════════════')
L.push(`-- Seeded ${CATEGORIES.length} category, ${keep.length} products, ${PROMOS.length} promos + default settings.`)
L.push(`-- Admin upgrade — run in the SQL editor (not from a client session):`)
L.push(`--   update public.profiles set role='admin' where id = (select id from auth.users where email='admin@healthharmony.com');`)
L.push('-- ═══════════════════════════════════════════════════════════════')
L.push('')

writeFileSync(join(root, 'supabase', 'seed.sql'), L.join('\n') + '\n')
console.log(`seed.sql written: ${keep.length} products, ${CATEGORIES.length} categories, ${PROMOS.length} promos; skipped ${unapproved.length} unapproved regulated products`)
